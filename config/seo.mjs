import { readdir, readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { loadEnv } from "vite";

export function readSeoConfig() {
  const env = loadEnv(process.env.NODE_ENV || "production", process.cwd(), "PUBLIC_");
  if (!env.PUBLIC_SITE_URL) {
    throw new Error("Définir PUBLIC_SITE_URL dans .env ou dans les variables de build de l’hébergeur.");
  }
  const site = new URL(env.PUBLIC_SITE_URL);
  if (site.protocol !== "https:" || site.pathname !== "/" || site.search || site.hash || site.username || site.password) {
    throw new Error("PUBLIC_SITE_URL doit être une origine HTTPS, sans chemin, paramètres ou identifiants.");
  }
  return {
    site: site.origin,
    noindex: env.PUBLIC_NOINDEX === "true" || process.env.VERCEL_ENV === "preview" ||
      ["deploy-preview", "branch-deploy"].includes(process.env.CONTEXT || ""),
  };
}

const escapeXml = (value) => value.replace(/[<>&"']/g, (character) => ({
  "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;", "'": "&apos;",
})[character]);

export function sitemapXml(site, pages) {
  const urls = [...new Set(pages.map(({ pathname }) => pathname.replace(/^\/+|\/+$/g, "")))]
    .filter((path) => !/^(admin|404)(\/|$)/.test(path))
    .map((path) => new URL(path ? `/${path}/` : "/", site).href);
  return '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    urls.map((url) => `  <url><loc>${escapeXml(url)}</loc></url>`).join("\n") + "\n</urlset>\n";
}

// The Studio is generated by @sanity/astro and has its own layout.
// Set its robots metadata in the static output without changing dependency files.
export function seoAssets({ site, noindex }) {
  return {
    name: "courant-seo-assets",
    hooks: {
      "astro:build:done": async ({ dir, pages }) => {
        async function markHtml(directory, admin = false) {
          for (const entry of await readdir(directory, { withFileTypes: true })) {
            const url = new URL(entry.name + (entry.isDirectory() ? "/" : ""), directory);
            const isAdmin = admin || (directory.href === dir.href && entry.name === "admin");
            if (entry.isDirectory()) await markHtml(url, isAdmin);
            else if (entry.name.endsWith(".html") && (noindex || isAdmin)) {
              const html = await readFile(url, "utf8");
              await writeFile(url, html.replace(/<head([^>]*)>/i,
                '<head$1><meta name="robots" content="noindex, follow">'));
            }
          }
        }
        await markHtml(dir);
        await writeFile(new URL("sitemap.xml", dir), sitemapXml(site, noindex ? [] : pages));
        // Keep pages crawlable so that crawlers can actually read the noindex directive.
        await writeFile(new URL("robots.txt", dir), "User-agent: *\nAllow: /\n" +
          (noindex ? "" : `\nSitemap: ${new URL("/sitemap.xml", site).href}\n`));
      },
    },
  };
}
